import crypto from 'crypto';
import fs from 'fs/promises';
import path from 'path';

import firmwareRepository from '../repositories/firmwareRepository';
import AppError from '../errors/AppError';
import logger from '../utils/logger';

const FIRMWARE_ROOT = process.env.FIRMWARE_ROOT || '/var/lib/cattle_tracker/firmwares';

// Folder of the binaries, for res.sendFile({ root }): files are served by name, never by path
export const FIRMWARE_DIR = path.resolve(FIRMWARE_ROOT);

// First byte of an ESP32/ESP8266 application image
const ESP_IMAGE_MAGIC = 0xe9;

const PG_UNIQUE_VIOLATION = '23505';

// Binary names generated by create(); cleanupFiles() never touches anything else in the folder
const FILENAME_REGEX = /^fw_\d+_\d+\.\d+\.\d+\.bin$/;

// Unreferenced files younger than this may be an upload in progress (written before its row)
const MIN_ORPHAN_AGE_MS = 60 * 60 * 1000;

function hash(algorithm, buffer) {
  return crypto.createHash(algorithm).update(buffer).digest('hex');
}

const firmwareService = {

  async getAll() {
    return firmwareRepository.findAll();
  },

  async get(id) {
    return firmwareRepository.findById(id);
  },

  // values: { code, version, notes } validated by firmwareValidator.
  // file: multer file (memory storage), checked here
  async create(values, file, userId) {
    const { code } = values;

    if (!file?.buffer?.length || file.buffer[0] !== ESP_IMAGE_MAGIC) {
      throw new AppError('INVALID_FIRMWARE', 400, 'file must be an ESP firmware image (.bin)');
    }

    if (await firmwareRepository.findByCode(code)) {
      throw new AppError('FIRMWARE_CODE_IN_USE', 409);
    }

    const filename = `fw_${code}_${values.version}.bin`;
    const filepath = path.join(FIRMWARE_ROOT, filename);

    try {
      await fs.writeFile(filepath, file.buffer, { flag: 'wx' });
    } catch (err) {
      // Code and version are unique even among deleted firmwares (firmwares_*_key): the file
      // belongs to a deleted one, and the insert would fail anyway
      if (err.code === 'EEXIST') {
        throw new AppError('FIRMWARE_VERSION_IN_USE', 409);
      }

      throw err;
    }

    try {
      return await firmwareRepository.create({
        code,
        version: values.version,
        filename,
        size: file.buffer.length,
        md5: hash('md5', file.buffer),
        sha256: hash('sha256', file.buffer),
        notes: values.notes,
        createdBy: userId,
      });
    } catch (err) {
      // If it can't be removed now, cleanupFiles() will
      await fs.unlink(filepath).catch((unlinkErr) => {
        logger.error({
          message: 'Failed to delete firmware file after a failed create',
          filepath,
          error: unlinkErr,
        });
      });

      if ((err.cause?.code ?? err.code) === PG_UNIQUE_VIOLATION) {
        throw new AppError('FIRMWARE_VERSION_IN_USE', 409);
      }

      throw err;
    }
  },

  // The file is kept: commands already delivered may still download it (see cleanupFiles)
  async delete(id) {
    return firmwareRepository.delete(id);
  },

  // Weekly job: delete binaries no firmware needs anymore. Covers files left by failed creates
  // and those of deleted firmwares once no OTA command is using them.
  async cleanupFiles() {
    const [entries, inUse] = await Promise.all([
      fs.readdir(FIRMWARE_DIR, { withFileTypes: true }),
      firmwareRepository.findFilenamesInUse(),
    ]);

    const candidates = entries
      .filter((entry) => entry.isFile() && FILENAME_REGEX.test(entry.name))
      .filter((entry) => !inUse.has(entry.name))
      .map((entry) => path.join(FIRMWARE_DIR, entry.name));

    const now = Date.now();
    const results = await Promise.allSettled(candidates.map(async (filepath) => {
      const { mtimeMs } = await fs.stat(filepath);

      if (now - mtimeMs < MIN_ORPHAN_AGE_MS) {
        return null;
      }

      await fs.unlink(filepath);
      return filepath;
    }));

    const deleted = results.filter((r) => r.status === 'fulfilled' && r.value).map((r) => r.value);
    const failed = results.filter((r) => r.status === 'rejected');

    failed.forEach((r) => logger.error({ message: 'Failed to delete firmware file', error: r.reason }));

    return { deleted: deleted.map((filepath) => path.basename(filepath)), failed: failed.length };
  },

  // Firmware whose binary is available (its file is FIRMWARE_DIR/filename), or null
  async getFile(code) {
    const firmware = await firmwareRepository.findByCode(code);

    if (!firmware) {
      return null;
    }

    const filepath = path.join(FIRMWARE_ROOT, firmware.filename);

    try {
      await fs.access(filepath);
    } catch {
      return null;
    }

    return firmware;
  },

};

export default firmwareService;
